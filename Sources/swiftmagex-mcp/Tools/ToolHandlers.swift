            )
        } catch let error as SwiftMageXError {
            return errorResult(error)
        }
    }

    // MARK: - Helpers

    /// Builds the human-readable summary that accompanies every tool result.
    /// The first line is `OK`; subsequent lines list each absolute path with
    /// its format and pixel dimensions — agents can parse this trivially, and
    /// humans can read it without re-decoding the file.
    private static func summaryText(
        for images: [WrittenImage],
        provider: String? = nil
    ) -> String {
        var lines = ["OK"]
        if let provider = provider {
            lines.append("provider: \(provider)")
        }
        for image in images {
            lines.append("\(image.path.path) (\(image.format.rawValue) \(image.width)x\(image.height))")
        }
        return lines.joined(separator: "\n")
    }

    /// Maps a ``SwiftMageXError`` into the `isError: true` result envelope.
    /// The category string is the same one the CLI reports in its JSON
    /// envelope (spec §13), so an agent can branch on it.
    private static func errorResult(_ error: SwiftMageXError) -> CallTool.Result {
        let text = "[\(error.category)] \(error.message)"
        return CallTool.Result(
            content: [.text(text: text, annotations: nil, _meta: nil)],
            isError: true
        )
    }
}
